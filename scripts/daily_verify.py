#!/usr/bin/env python3
"""Daily DHP verification: run the full suite + conformance, commit the evidence.

Produces daily/YYYY-MM-DD.md with real numbers. Only commits if the run
completes; a failing suite is still committed (honest signal) but flagged.
"""
import datetime
import subprocess
import sys
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATE = datetime.date.today().isoformat()
OUT = os.path.join(ROOT, "daily", f"{DATE}.md")


def run(cmd, timeout=300):
    try:
        r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True,
                           timeout=timeout)
        return r.returncode, (r.stdout + r.stderr)[-3000:]
    except subprocess.TimeoutExpired:
        return -1, "TIMEOUT"


def main():
    os.makedirs(os.path.join(ROOT, "daily"), exist_ok=True)

    # 1. pytest
    rc1, out1 = run([sys.executable, "-m", "pytest", "tests/", "-q"], 600)
    # 2. conformance
    rc2, out2 = run(["dhp-conform"], 300)

    # extract the headline numbers
    pytest_line = [l for l in out1.splitlines()
                   if "passed" in l or "failed" in l or "error" in l]
    conform_line = [l for l in out2.splitlines()
                    if "passed" in l or "failed" in l]

    status = "GREEN" if (rc1 == 0 and rc2 == 0) else "RED"
    lines = [
        f"# DHP daily verification — {DATE}",
        "",
        f"**Status: {status}**",
        "",
        "## pytest",
        "",
        f"- exit: {rc1}",
        f"- result: {pytest_line[-1].strip() if pytest_line else 'n/a'}",
        "",
        "## conformance (`dhp-conform`)",
        "",
        f"- exit: {rc2}",
        f"- result: {conform_line[-1].strip() if conform_line else 'n/a'}",
        "",
        "## notes",
        "",
        ("All green — no action needed." if status == "GREEN"
         else "FAILURE — investigate before next release."),
        "",
        "_Generated by `scripts/daily_verify.py`. Raw output truncated to last 3000 chars per suite._",
    ]
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT} status={status}")
    return 0 if status == "GREEN" else 1


if __name__ == "__main__":
    sys.exit(main())
